"""The coverage matrix: its jolty column is what its fixtures find; its sources hold.

The matrix in `benchmarks/coverage/` is regenerated by `scripts/bench --coverage`, which
runs every simulator; these tests run jolty's fixtures alone, and fail when the
committed matrix says otherwise, as the reference pages fail when their source changes.
"""

import typing

import documented
import matrix
import pytest
from capabilities import JOLTY_ANALYSES, Known, Read, fixtures, ngspice_only
from measuring import load
from simulators import Simulator, Unsupported

from jolty import plan

FIXTURES = {fixture.key: fixture for fixture in fixtures()}
COMMITTED = matrix.SuiteResults.model_validate(load(matrix.RESULTS))


@pytest.mark.parametrize("key", list(FIXTURES))
def test_jolty_column_is_what_its_fixture_finds(key: str) -> None:
    fixture = FIXTURES[key]
    cell = matrix.run(fixture, Simulator.JOLTY)
    document = matrix.SuiteResults(
        fixtures={
            key: matrix.FixtureResults(
                category=fixture.category,
                name=fixture.name,
                source="",
                known=None,
                cells={
                    "jolty": cell,
                    **{
                        name: found
                        for name, found in COMMITTED.fixtures[key].cells.items()
                        if name != "jolty"
                    },
                },
            )
        }
    )
    matrix.rejudge(document, FIXTURES)
    assert document.fixtures[key].cells["jolty"].status == (
        COMMITTED.fixtures[key].cells["jolty"].status
    )


def test_every_row_is_in_the_matrix() -> None:
    assert list(COMMITTED.fixtures) == list(FIXTURES)


def test_jolty_analyses_are_the_plans() -> None:
    members = [member.__name__ for member in typing.get_args(plan.Analysis.__value__)]
    assert f"jolty.plan.Analysis: {', '.join(members)}" == JOLTY_ANALYSES


def test_documented_cells_cite_a_row_and_a_source() -> None:
    for key, given in documented.CELLS.items():
        assert key in FIXTURES
        for name, (status, source) in given.items():
            assert name in documented.TITLES
            assert status in {"documented", "unsupported"}
            assert source


def test_a_number_beyond_the_tolerance_disagrees() -> None:
    known = Known(values={"v(out)": 1.0, "i(v1)": 1e-3}, source="a test")
    # Each number is judged against the largest of its kind, so the current's error
    # of 2e-9 A is 2e-6 of 1 mA, beyond the tolerance of 1e-6, and the voltage's 5e-7
    # of 1 V is within it.
    found = {"v(out)": complex(1 + 5e-7), "i(v1)": complex(1e-3 + 2e-9)}
    status, evidence = matrix.judge(known, found, None)
    assert status is matrix.Status.DISAGREED
    assert evidence.startswith("i(v1)")
    within = {"v(out)": complex(1 + 5e-7), "i(v1)": complex(1e-3 + 5e-10)}
    assert matrix.judge(known, within, None)[0] is matrix.Status.AGREED


def test_tline_agrees_with_closed_form() -> None:
    """Lossless transmission line probes via Transient and agrees with closed form."""
    fixture = FIXTURES["tline"]
    cell = matrix.run(fixture, Simulator.JOLTY)
    assert cell.found is not None
    assert fixture.known is not None
    found = {name: complex(real, imag) for name, (real, imag) in cell.found.items()}
    status, evidence = matrix.judge(fixture.known, found, None)
    assert status is matrix.Status.AGREED, evidence


def test_ngspice_only_reads_declared_names() -> None:
    """An `ngspice_only` row reads its declared keys instead of returning empty `{}`."""
    row = ngspice_only(
        "probe",
        "Probe divider",
        ("* divider", "V1 a 0 2", "R1 a out 1k", "R2 out 0 1k"),
        ("op",),
        {"v(out)": Read(ngspice="v(out)", xyce="V(OUT)")},
        {"v(out)": 1.0},
        "closed form: halving divider",
        xyce=Unsupported("test"),
    )
    assert not isinstance(row.jolty, Unsupported)
    values = row.jolty()
    assert list(values) == ["v(out)"]
    # Exact 1:1 divider ratio: 2 V / 2 = 1 V, within floating-point rounding (1e-12).
    assert abs(values["v(out)"] - 1.0) < 1e-12
