"""The coverage matrix: its jolty column is what its probes find, and its sources hold.

The matrix in `perf/coverage/` is regenerated by `scripts/bench --coverage`, which runs
every simulator; these tests run jolty's probes alone, and fail when the committed
matrix says otherwise, as the reference pages fail when their source changes.
"""

import typing

import documented
import matrix
import pytest
from probes import JOLTY_ANALYSES, Known, rows

from jolty import plan

ROWS = {row.key: row for row in rows()}
COMMITTED = matrix.Document.model_validate_json(
    matrix.RESULTS.read_text(encoding="utf-8")
)


@pytest.mark.parametrize("key", list(ROWS))
def test_jolty_column_is_what_its_probe_finds(key: str) -> None:
    row = ROWS[key]
    cell = matrix.probe(row, matrix.Simulator.JOLTY, matrix.COVERAGE.parents[1])
    document = matrix.Document(
        rows={
            key: matrix.Line(
                category=row.category,
                name=row.name,
                source="",
                known=None,
                cells={
                    "jolty": cell,
                    **{
                        name: found
                        for name, found in COMMITTED.rows[key].cells.items()
                        if name != "jolty"
                    },
                },
            )
        }
    )
    matrix.rejudge(document, ROWS)
    assert document.rows[key].cells["jolty"].status == (
        COMMITTED.rows[key].cells["jolty"].status
    )


def test_every_row_is_in_the_matrix() -> None:
    assert list(COMMITTED.rows) == list(ROWS)


def test_jolty_analyses_are_the_plans() -> None:
    members = [member.__name__ for member in typing.get_args(plan.Analysis.__value__)]
    assert f"jolty.plan.Analysis: {', '.join(members)}" == JOLTY_ANALYSES


def test_documented_cells_cite_a_row_and_a_source() -> None:
    for key, given in documented.CELLS.items():
        assert key in ROWS
        for name, (status, source) in given.items():
            assert name in documented.TITLES
            assert status in {"documented", "not offered"}
            assert source


def test_a_number_beyond_the_tolerance_disagrees() -> None:
    known = Known(values={"v(out)": 1.0, "i(v1)": 1e-3}, source="a test")
    # Each number is judged against the largest of its kind, so the current's error
    # of 2e-9 A is 2e-6 of 1 mA, beyond the tolerance of 1e-6, and the voltage's 5e-7
    # of 1 V is within it.
    found = {"v(out)": complex(1 + 5e-7), "i(v1)": complex(1e-3 + 2e-9)}
    status, evidence = matrix.judge(known, found, None)
    assert status is matrix.Status.DISAGREES
    assert evidence.startswith("i(v1)")
    within = {"v(out)": complex(1 + 5e-7), "i(v1)": complex(1e-3 + 5e-10)}
    assert matrix.judge(known, within, None)[0] is matrix.Status.AGREES
